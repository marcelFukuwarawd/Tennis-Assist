#!/usr/bin/env python3
"""Generates values/strings.xml (English) and values-pt/strings.xml (Portuguese) from tools/strings.tsv
and checks that every R.string.* used in the code exists."""
import re, sys, pathlib, html
root = pathlib.Path(__file__).resolve().parent.parent
rows = []
for line in (root / "tools/strings.tsv").read_text(encoding="utf-8").splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    parts = line.split("\t")
    if len(parts) != 3:
        sys.exit(f"bad line: {line!r}")
    rows.append(parts)
keys = [r[0] for r in rows]
dupes = {k for k in keys if keys.count(k) > 1}
if dupes:
    sys.exit(f"duplicate keys: {dupes}")
def esc(s):
    s = html.escape(s, quote=False).replace("'", "\\'").replace('"', '\\"')
    return s
for idx, folder in ((1, "values"), (2, "values-pt")):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen_strings.py from tools/strings.tsv. Do not edit by hand. -->", "<resources>"]
    for r in rows:
        attr = ' translatable="false"' if r[0] == "app_name" and idx == 2 else ""
        if r[0] == "app_name" and idx == 2:
            continue
        out.append(f'    <string name="{r[0]}"{attr}>{esc(r[idx])}</string>')
    out.append("</resources>")
    (root / f"app/src/main/res/{folder}/strings.xml").write_text("\n".join(out) + "\n", encoding="utf-8")
used = set()
for f in (root / "app/src/main/java").rglob("*.kt"):
    used |= set(re.findall(r"R\.string\.([a-zA-Z0-9_]+)", f.read_text(encoding="utf-8")))
for f in (root / "app/src/main").rglob("*.xml"):
    used |= set(re.findall(r"@string/([a-zA-Z0-9_]+)", f.read_text(encoding="utf-8")))
missing = sorted(used - set(keys))
if missing:
    print("MISSING:", " ".join(missing))
    sys.exit(1)
print(f"{len(rows)} strings OK, {len(set(keys) - used)} unused")
